"""Schematic + PCB for the TJ Backplane (power splitter)."""
import json
import os
import sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import pcbnew
import schgen
import netcheck
from backplane import D, REV, OUTPUTS
from pcbgen import Builder
from route_board import route

OUT = os.path.join(HERE, '..', 'tj_backplane')
SCR = os.environ.get('TJ_BUILD', os.path.join(HERE, '_build'))
os.makedirs(SCR, exist_ok=True)
D.rev = REV
NOTES = [
    'Splits the 12V and 5V supplies to up to seven TJ Brain boards (F1 F2 F3 M1 M2 BAR SPARE).',
    'USB: a commercial 7-port powered USB 2.0 hub, powered from HUB 5V, one USB cable per brain (Teensy micro-USB).',
    'Each output is protected by its own resettable fuses; LED off = fuse tripped or rail missing.',
    'Generated by CAD/KiCad/generator (python3 build_backplane.py).',
]
root_uuid, sheet_uuids = schgen.write(D, OUT, NOTES)
uuids = {'root': root_uuid, 'sheets': sheet_uuids}
tree = netcheck.export(os.path.join(OUT, 'tj_backplane.kicad_sch'), os.path.join(SCR, 'tj_backplane.net'))
probs = netcheck.compare(D, tree)
print('\n'.join(probs) if probs else 'NETLIST MATCHES DESIGN')

W, H = 200.0, 85.0
P = {}
LAB = []


def grp(name):
    return [p.ref for p in D.parts if p.group == name and not p.ref.startswith('#')]


def put(ref, x, y, r=0):
    P[ref] = (x, y, r)


# inputs on the left edge (wire entry towards the edge)
put('J1', 5.7, 18, 270)
put('J2', 5.7, 40, 270)
g12 = grp('12V input')        # J1 D C R LED
put(g12[1], 21, 13); put(g12[2], 30, 10); put(g12[3], 42, 15.5); put(g12[4], 48, 15.5)
g5 = grp('5V input')          # J2 D C R LED
put(g5[1], 21, 63); put(g5[2], 27, 72); put(g5[3], 18, 79); put(g5[4], 24, 79)
gh = grp('USB hub supply (5V, 2A PTC)')  # F J3 R LED
put(gh[0], 178, 41); put(gh[1], W - 5.7, 49, 90); put(gh[2], 186, 50); put(gh[3], 186, 53.5)
tp = grp('Test points & mounting')
put(tp[0], 14, 30); put(tp[1], 14, 24.5); put(tp[2], 14, 35)
put(tp[3], 4, 4); put(tp[4], W - 4, 4); put(tp[5], 4, H - 4); put(tp[6], W - 4, H - 4)
X0 = [40 + 21 * k for k in range(len(OUTPUTS))]
for k, name in enumerate(OUTPUTS):
    f12, f5, j, r12, l12, r5, l5 = grp('Output %d (%s)' % (k + 1, name))
    x0 = X0[k]
    put(f12, x0, 27); put(f5, x0, 42)
    put(j, x0 + 2, 70)
    put(r12, x0 + 12.5, 27.5); put(l12, x0 + 12.5, 31)
    put(r5, x0 + 12.5, 48); put(l5, x0 + 12.5, 51.5)
    LAB.append(('12V', x0 + 16.4, 31, 0.8)); LAB.append(('5V', x0 + 16.4, 51.5, 0.8))

b = Builder(D, uuids, W, H)
b.outline()
b.add_parts(P)
# +12V bus (top layer) along y=20, stubs to every 12V fuse
p12 = b.pad_pos('J1', 1)
b.track([p12, (p12[0], 20), (X0[-1], 20)], 3.0, pcbnew.F_Cu, '+12V')
for k, name in enumerate(OUTPUTS):
    f12, f5, j, r12, l12, r5, l5 = grp('Output %d (%s)' % (k + 1, name))
    x0 = X0[k]
    a = b.pad_pos(f12, 1)
    b.track([(a[0], 20), a], 2.0, pcbnew.F_Cu, '+12V')
    # fused 12V to connector pin 1 on the bottom layer (crosses the 5V plane)
    q = b.pad_pos(f12, 2); c = b.pad_pos(j, 1)
    b.track([q, (q[0], 33), (x0 + 8.6, 36.5), (x0 + 8.6, 58), (c[0], 64.6), c], 1.5, pcbnew.B_Cu, '+12V_%s' % name)
    rr = b.pad_pos(r12, 1)
    b.track([q, (rr[0] - 1.5, q[1]), (rr[0] - 1.5, rr[1]), rr], 0.4, pcbnew.F_Cu, '+12V_%s' % name)
    # fused 5V to connector pin 2 (top layer)
    q = b.pad_pos(f5, 2); c = b.pad_pos(j, 2)
    b.track([q, (c[0], q[1] + 3), c], 2.0, pcbnew.F_Cu, '+5V_%s' % name)
    rr = b.pad_pos(r5, 1)
    b.track([q, (q[0] + 2.5, q[1] + 2.5), (rr[0] - 1.5, rr[1]), rr], 0.4, pcbnew.F_Cu, '+5V_%s' % name)
rl = b.pad_pos(g12[3], 1)
b.track([rl, (rl[0], 20)], 0.6, pcbnew.F_Cu, '+12V')
c1 = b.pad_pos(g12[2], 1)
b.track([c1, (c1[0], 20)], 1.5, pcbnew.F_Cu, '+12V')
d1 = b.pad_pos(g12[1], 1)
b.track([d1, (d1[0], 20)], 1.5, pcbnew.F_Cu, '+12V')
print('GND fanout vias', b.gnd_fanout())
# zones: +5V plane on top (inputs -> fuses), GND on bottom and on remaining top area
z5 = [(2, 34), (W - 12, 34), (W - 12, 57), (36, 57), (36, 76), (2, 76)]
b.zone('+5V', pcbnew.F_Cu, z5, priority=2, clearance=0.4, solid_pads=True)
inset = 0.5
full = [(inset, inset), (W - inset, inset), (W - inset, H - inset), (inset, H - inset)]
b.zone('GND', pcbnew.B_Cu, full, priority=0, clearance=0.4)
b.zone('GND', pcbnew.F_Cu, full, priority=0, clearance=0.4)
for p in D.parts:
    if p.silk and p.ref in b.fps and p.ref.startswith('J'):
        q = b.fps[p.ref].GetPosition()
        x, y = pcbnew.ToMM(q.x), pcbnew.ToMM(q.y)
        if p.ref in ('J1', 'J2'):
            b.text(p.silk, 15.5, y + (2.5 if p.ref == 'J1' else 7.6), 1.2, bold=True, angle=90)
        elif p.ref == 'J3':
            b.text('HUB 5V OUT', 192.5, 57.5, 1.0, bold=True)
        else:
            b.text(p.silk, x + 2.1, 80.0, 1.6, bold=True)
for t, x, y, s in LAB:
    b.text(t, x, y, s, just=-1)
for ref, fp in b.fps.items():
    if ref.startswith(('R', 'C', 'D', 'TP', 'H', 'F')):
        fp.Reference().SetVisible(False)
b.text('TJ BACKPLANE  rev %s' % REV, 112, 6.5, 2.0, bold=True)
b.text('12V / 5V splitter for the TJ Brain boards - order with 2 oz copper', 112, 10, 1.0)
b.text('USB: 7-port powered USB 2.0 hub (fed from HUB 5V), one cable per brain', 112, 12.6, 1.0)
b.text('OUT pinout: 1 +12V  2 +5V  3/4 GND   fuses 12V 3A, 5V 5A (resettable)', 112, 15.2, 1.0)
placed = os.path.join(SCR, 'tj_backplane_placed.kicad_pcb')
b.save(placed)
routed = os.path.join(SCR, 'tj_backplane_routed.kicad_pcb')
widths = {'+5V_HUB': 1.0, '+12V': 1.0, '+5V': 1.0}
failed = route(placed, routed, W, H, widths, order_first=('+5V_HUB',), skip=('GND',))
print('failed', failed)

# ------------------------------------------------------------------ finish + export
import shutil
import export
from route_board import finish
final = os.path.join(OUT, 'tj_backplane.kicad_pcb')
shutil.copy(routed, final)
finish(final, os.path.join(SCR, 'bp_drc.rpt'))
export.project_file(os.path.join(OUT, 'tj_backplane.kicad_pro'), 'tj_backplane',
                    [('Power', 1.5, ['+12V', '+5V', '+5V_*', '+12V_*'])])
export.lib_tables(OUT)
counts, unc = export.drc(final, os.path.join(SCR, 'bp_drc_final.rpt'))
print('DRC', dict(counts), unc)
export.fab(final, OUT, 'tj_backplane', D)
print('exported')
