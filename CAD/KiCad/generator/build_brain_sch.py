import os, sys, json
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import schgen, netcheck
from brain import D, REV
D.rev = REV
OUT = os.path.join(HERE, '..', 'tj_brain')
SCR = os.environ.get('TJ_BUILD', os.path.join(HERE, '_build'))
os.makedirs(SCR, exist_ok=True)
NOTES = [
    'One brain board per unit (female 1-3, male 1-2, bar). Unit role = DIP switch SW1 (read by firmware).',
    'Host link: USB from the backplane hub straight into the Teensy micro-USB. Power: Mini-Fit Jr 4p (+12V, +5V, GND, GND).',
    'Female: board on the static part, DA-15 BODY cable into the rotating body (pinout compatible with the ZKM electronic box).',
    'Male / bar: same board, peripherals on the JST / terminal connectors or on the DA-15.',
    'Generated by CAD/KiCad/generator (python3 build_brain.py). Edit brain.py and regenerate rather than editing by hand.',
]
root_uuid, sheet_uuids = schgen.write(D, OUT, NOTES)
json.dump({'root': root_uuid, 'sheets': sheet_uuids, 'parts': {p.ref: [p.sheet, p.uuid] for p in D.parts}},
          open(os.path.join(HERE, 'brain_uuids.json'), 'w'), indent=1)
tree = netcheck.export(os.path.join(OUT, 'tj_brain.kicad_sch'), os.path.join(SCR, 'tj_brain.net'))
probs = netcheck.compare(D, tree)
print('\n'.join(probs) if probs else 'NETLIST MATCHES DESIGN')
